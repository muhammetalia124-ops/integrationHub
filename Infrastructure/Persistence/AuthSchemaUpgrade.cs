using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;

namespace IntegrationHub.Infrastructure.Persistence;

internal static class AuthSchemaUpgrade
{
    private const string Sql = """
        ALTER TABLE "Auth"."Users" ADD COLUMN IF NOT EXISTS "IsEmailVerified" boolean NOT NULL DEFAULT FALSE;
        ALTER TABLE "Auth"."Users" ALTER COLUMN "IsEmailVerified" SET DEFAULT FALSE;
        ALTER TABLE "Auth"."Users" ADD COLUMN IF NOT EXISTS "UsernameChangedAt" timestamp with time zone NULL;

        CREATE TABLE IF NOT EXISTS "Auth"."AuthVerificationCodes" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY,
            "Email" character varying(256) NOT NULL,
            "Purpose" character varying(32) NOT NULL,
            "CodeHash" character varying(64) NOT NULL,
            "Attempts" integer NOT NULL DEFAULT 0,
            "ExpiresAtUtc" timestamp with time zone NOT NULL,
            "CreatedAtUtc" timestamp with time zone NOT NULL DEFAULT now(),
            "ConsumedAtUtc" timestamp with time zone NULL,
            CONSTRAINT "PK_AuthVerificationCodes" PRIMARY KEY ("Id")
        );
        CREATE INDEX IF NOT EXISTS "IX_AuthVerificationCodes_Lookup"
            ON "Auth"."AuthVerificationCodes" ("Email", "Purpose");

        CREATE TABLE IF NOT EXISTS "Auth"."RefreshTokens" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY,
            "UserId" integer NOT NULL,
            "TokenHash" character varying(128) NOT NULL,
            "ExpiresAtUtc" timestamp with time zone NOT NULL,
            "CreatedAtUtc" timestamp with time zone NOT NULL,
            "RevokedAtUtc" timestamp with time zone NULL,
            "ReplacedByTokenHash" character varying(128) NULL,
            "UserAgent" character varying(512) NULL,
            CONSTRAINT "PK_RefreshTokens" PRIMARY KEY ("Id")
        );
        CREATE INDEX IF NOT EXISTS "IX_RefreshTokens_TokenHash"
            ON "Auth"."RefreshTokens" ("TokenHash");
        CREATE INDEX IF NOT EXISTS "IX_RefreshTokens_User_Expires"
            ON "Auth"."RefreshTokens" ("UserId", "ExpiresAtUtc");
        """;

    public static async Task ApplyAsync(IServiceScopeFactory scopeFactory, CancellationToken ct)
    {
        await using var scope = scopeFactory.CreateAsyncScope();
        var db = scope.ServiceProvider.GetRequiredService<UserDbContext>();
        await db.Database.ExecuteSqlRawAsync(Sql, ct);
    }
}
